import test from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { WebSocket } from 'ws';
import { createHash } from 'node:crypto';
import { createApplication } from '../server.mjs';

test('public lobby, private code search, passwords and revocable passwordless invitation links', { timeout: 20000 }, async () => {
  const mails = [], sockets = [];
  const server = createApplication({ password: 'local-admin-password-32', origin: 'http://127.0.0.1:3210', database: ':memory:', sendMail: async mail => mails.push(mail) });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  const api = async (route, token = '', value, method = value ? 'POST' : 'GET') => {
    const response = await fetch(base + route, { method, headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: 'Bearer ' + token } : {}) }, body: value ? JSON.stringify(value) : undefined });
    return { status: response.status, body: await response.json() };
  };
  const register = async name => {
    const email = name + '@example.invalid';
    await api('/api/auth/code', '', { email, purpose: 'register' });
    return (await api('/api/auth/register', '', { email, nickname: name, password: 'Test1234', code: mails.at(-1).text.match(/\d{6}/)[0] })).body;
  };
  const connect = async ticket => {
    const socket = new WebSocket(base.replace('http:', 'ws:') + '/api/rooms/socket', 'cpt.' + ticket); sockets.push(socket);
    const ready = once(socket, 'message'); await once(socket, 'open'); await ready; return socket;
  };
  try {
    const host = await register('Host'), guest = await register('Guest');
    assert.equal((await api('/api/rooms/lobby')).status, 401);
    const created = await api('/api/rooms/create', host.token, { port: 25565, title: 'Private room', password: 'Room123', public: false });
    assert.equal(created.status, 200);
    const code = created.body.code;
    const invitationStatus = link => api('/api/rooms/invitation-status', '', { code: link.split('#')[1].split('.')[0], proof: createHash('sha256').update(link.split('#')[1]).digest('hex') });
    assert.match(created.body.shareLink, new RegExp('/room#' + code + '\\.[a-f0-9]{64}$'));
    await connect(created.body.ticket);
    assert.equal((await invitationStatus(created.body.shareLink)).body.state, 'valid');
    assert.equal((await api('/api/rooms/invitation-status', '', { code, proof: 'bad' })).status, 400);
    assert.equal((await api('/api/rooms/lobby', guest.token)).body.rooms.length, 0);
    assert.equal((await api('/api/rooms/lobby?code=' + code, guest.token)).body.rooms[0].passwordRequired, true);
    assert.equal((await api('/api/rooms/lobby?code=bad', guest.token)).status, 400);
    assert.equal((await api('/api/rooms/join', guest.token, { code, password: 'badpass' })).status, 403);
    const byPassword = await api('/api/rooms/join', guest.token, { code, password: 'Room123' });
    assert.equal(byPassword.status, 200);
    const member = await connect(byPassword.body.ticket);
    assert.equal((await api('/api/rooms/settings', guest.token, { code, public: true })).status, 403);
    assert.equal((await api('/api/rooms/settings', host.token, { code, public: true, rotateInvite: 'bad' })).status, 400);
    assert.equal((await api('/api/rooms/lobby', guest.token)).body.rooms.length, 0);
    const closed = once(member, 'close'); await api('/api/rooms/leave', guest.token, {}); await closed;
    const invite = created.body.shareLink.split('.').at(-1);
    assert.equal((await api('/api/rooms/join', guest.token, { code, invite: 'b'.repeat(64), password: 'Room123' })).status, 403);
    const byInvite = await api('/api/rooms/join', guest.token, { code, invite });
    assert.equal(byInvite.status, 200);
    const updated = await api('/api/rooms/settings', host.token, { code, public: true, title: 'Public room', rotateInvite: true });
    assert.equal(updated.status, 200);
    assert.notEqual(updated.body.shareLink, created.body.shareLink);
    assert.equal((await invitationStatus(created.body.shareLink)).body.state, 'expired');
    assert.equal((await invitationStatus(updated.body.shareLink)).body.state, 'valid');
    assert.equal((await api('/api/rooms/join', guest.token, { code, invite })).status, 403);
    const stale = new WebSocket(base.replace('http:', 'ws:') + '/api/rooms/socket', 'cpt.' + byInvite.body.ticket);
    await once(stale, 'error');
    const lobby = await api('/api/rooms/lobby', guest.token);
    assert.equal(lobby.body.rooms.length, 1); assert.equal(lobby.body.rooms[0].title, 'Public room');
    assert.equal(JSON.stringify(lobby.body).includes(invite), false);
    assert.equal(JSON.stringify(lobby.body).includes('Room123'), false);
    assert.equal(lobby.body.rooms[0].shareLink, undefined);
    const freshInvite = updated.body.shareLink.split('.').at(-1);
    const fresh = await api('/api/rooms/join', guest.token, { code, invite: freshInvite }); assert.equal(fresh.status, 200);
    const joined = await connect(fresh.body.ticket);
    assert.equal((await api('/api/rooms/mine', guest.token)).body.shareLink, undefined);
    const quit = once(joined, 'close'); await api('/api/rooms/leave', guest.token, {}); await quit;
    assert.equal((await api('/api/rooms/settings', host.token, { code, password: '' })).body.passwordRequired, false);
    assert.equal((await api('/api/rooms/join', guest.token, { code })).status, 200);
    assert.equal((await api('/api/rooms/settings', host.token, { code, public: 'yes' })).status, 400);
    await api('/api/rooms/settings', host.token, { code, public: false });
    assert.equal((await api('/api/rooms/lobby', guest.token)).body.rooms.length, 0);
    assert.equal((await api('/api/rooms/lobby?code=' + code, guest.token)).body.rooms.length, 1);
    const page = await fetch(base + '/room'); assert.equal(page.status, 200);
    assert.match(page.headers.get('referrer-policy'), /no-referrer/);
    assert.equal((await api('/api/rooms/mine', host.token)).body.shareLink, updated.body.shareLink);
    const admin = await fetch(base + '/api/admin/login', { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: 'http://127.0.0.1:3210' }, body: JSON.stringify({ password: 'local-admin-password-32' }) });
    const session = await admin.json(), cookie = admin.headers.get('set-cookie').split(';')[0];
    const detail = await fetch(base + '/api/admin/rooms/' + code, { headers: { Cookie: cookie } }).then(value => value.json());
    assert.equal(JSON.stringify(detail).includes(freshInvite), false);
    await fetch(base + '/api/admin/rooms/' + code, { method: 'PATCH', headers: { 'Content-Type': 'application/json', Cookie: cookie, Origin: 'http://127.0.0.1:3210', 'X-CSRF-Token': session.csrf }, body: JSON.stringify({ locked: true, reason: 'Test lock' }) });
    assert.equal((await api('/api/rooms/join', guest.token, { code, invite: freshInvite })).status, 403);
    assert.equal((await invitationStatus(updated.body.shareLink)).body.state, 'unavailable');
    await api('/api/rooms/leave', host.token, {});
    assert.equal((await invitationStatus(updated.body.shareLink)).body.state, 'expired');
    assert.equal((await api('/api/rooms/join', guest.token, { code, invite: freshInvite })).status, 404);
    const replacement = await api('/api/rooms/create', host.token, { port: 25565 });
    const ownerSocket = await connect(replacement.body.ticket);
    assert.notEqual(replacement.body.code, code);
    assert.equal((await invitationStatus(updated.body.shareLink)).body.state, 'expired');
    assert.equal((await invitationStatus(replacement.body.shareLink)).body.state, 'valid');
    const pendingJoin = await api('/api/rooms/join', guest.token, { code: replacement.body.code, invite: replacement.body.shareLink.split('.').at(-1) });
    const ownerClosed = once(ownerSocket, 'close'); ownerSocket.terminate(); await ownerClosed;
    for (let i = 0; i < 30 && (await invitationStatus(replacement.body.shareLink)).body.state !== 'expired'; i++) await new Promise(resolve => setTimeout(resolve, 10));
    assert.equal((await invitationStatus(replacement.body.shareLink)).body.state, 'expired');
    const invalidTicket = new WebSocket(base.replace('http:', 'ws:') + '/api/rooms/socket', 'cpt.' + pendingJoin.body.ticket);
    sockets.push(invalidTicket); await once(invalidTicket, 'error');
  } finally { for (const socket of sockets) socket.terminate(); await new Promise(resolve => setTimeout(resolve, 30)); await new Promise(resolve => server.close(resolve)); }
});
